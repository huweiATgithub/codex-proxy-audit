import { test, expect } from '@playwright/test';

const responseForList = (page) => page.waitForResponse((response) => new URL(response.url()).pathname === '/__demo/api/audits');
const params = (response) => Object.fromEntries(new URL(response.url()).searchParams);

test('grouped presets query directly, freeze dates during paging and refresh using the server date', async ({ page }) => {
  const failures = [];
  page.on('pageerror', (error) => failures.push(error.message));
  let today = '2026-10-09', contexts = 0;
  await page.route('**/__demo/api/view-context?**', (route) => {
    contexts++;
    return route.fulfill({ json: { today, timeZone: 'Asia/Shanghai' } });
  });
  const ui = page.frameLocator('iframe');
  const group = ui.getByRole('group', { name: '时间范围', exact: true });
  await page.goto('/');
  await expect(ui.locator('tbody tr')).toHaveCount(50);
  const recent = responseForList(page);
  await group.getByRole('button', { name: '最近三天', exact: true }).click();
  expect(params(await recent)).toMatchObject({ from: '2026-10-07', to: '2026-10-09', limit: '50' });
  await expect(group.locator('[aria-pressed="true"]')).toHaveCount(1);
  const before = contexts;
  today = '2026-10-10';
  const next = responseForList(page);
  await ui.getByRole('button', { name: '下一页', exact: true }).click();
  expect(params(await next)).toMatchObject({ from: '2026-10-07', to: '2026-10-09' });
  expect(contexts).toBe(before);
  const refreshed = responseForList(page);
  await ui.getByRole('button', { name: '刷新列表', exact: true }).click();
  expect(params(await refreshed)).toMatchObject({ from: '2026-10-08', to: '2026-10-10' });
  await expect(ui.locator('.cursor-pagination')).toContainText('第 1 页');
  await ui.getByRole('searchbox').fill('数据库');
  await ui.getByRole('combobox', { name: 'Client Key', exact: true }).click();
  await ui.getByRole('option').filter({ hasText: 'ck_platform' }).click();
  const filtered = responseForList(page);
  await group.getByRole('button', { name: '全部', exact: true }).click();
  expect(params(await filtered)).toMatchObject({ key: 'ck_platform', q: '数据库', limit: '50' });
  expect(contexts).toBe(before + 1);
  expect(failures).toEqual([]);
});

test('custom range selects both endpoints in one panel, supports keyboard input and cancels drafts', async ({ page }) => {
  const ui = page.frameLocator('iframe');
  const group = ui.getByRole('group', { name: '时间范围', exact: true });
  await page.goto('/');
  await expect(ui.locator('tbody tr')).toHaveCount(50);
  await ui.locator('[data-audit]').first().click();
  const selected = await ui.locator('[data-audit][aria-expanded="true"]').getAttribute('data-audit');
  const trigger = group.getByRole('button', { name: '自定义', exact: true });
  await trigger.click();
  const dialog = ui.getByRole('dialog', { name: '自定义时间范围', exact: true });
  await dialog.getByRole('button', { name: '2026-10-09', exact: true }).focus();
  await page.keyboard.press('ArrowLeft');
  await expect(dialog.getByRole('button', { name: '2026-10-08', exact: true })).toBeFocused();
  await expect(ui.locator(`[data-audit="${selected}"]`)).toHaveAttribute('aria-expanded', 'true');
  await dialog.getByRole('button', { name: '2026-10-09', exact: true }).click();
  await dialog.getByRole('button', { name: '2026-10-08', exact: true }).click();
  await expect(ui.locator('#date-from')).toHaveValue('2026-10-08');
  await expect(ui.locator('#date-to')).toHaveValue('2026-10-09');
  const custom = responseForList(page);
  await dialog.getByRole('button', { name: '应用', exact: true }).click();
  expect(params(await custom)).toMatchObject({ from: '2026-10-08', to: '2026-10-09' });
  await expect(trigger).toHaveAttribute('aria-pressed', 'true');
  await trigger.click();
  await ui.locator('#date-from').fill('2026-02-30');
  await expect(dialog.getByRole('alert')).toContainText('有效日期');
  await expect(dialog.getByRole('button', { name: '应用', exact: true })).toBeDisabled();
  await ui.locator('#date-from').press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await trigger.click();
  await expect(ui.locator('#date-from')).toHaveValue('2026-10-08');
  await ui.locator('#date-from').fill('');
  const unbounded = responseForList(page);
  await dialog.getByRole('button', { name: '应用', exact: true }).click();
  const query = params(await unbounded);
  expect(query.from).toBeUndefined(); expect(query.to).toBe('2026-10-09');
});

test('failed date reads preserve results and the unified control and calendar fit a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const ui = page.frameLocator('iframe');
  const group = ui.getByRole('group', { name: '时间范围', exact: true });
  await page.goto('/');
  await expect(ui.locator('tbody tr')).toHaveCount(50);
  let listReads = 0;
  page.on('request', (request) => { if (new URL(request.url()).pathname === '/__demo/api/audits') listReads++; });
  await page.route('**/__demo/api/view-context?**', (route) => route.fulfill({ status: 503, json: { error: { code: 'unavailable', message: '无法取得服务端日期。' } } }));
  await group.getByRole('button', { name: '最近三天', exact: true }).click();
  await expect(ui.getByRole('alert')).toContainText('无法取得服务端日期');
  await expect(group.getByRole('button', { name: '今天', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(ui.locator('tbody tr')).toHaveCount(50);
  expect(listReads).toBe(0);
  await group.getByRole('button', { name: '自定义', exact: true }).click();
  const dialog = ui.getByRole('dialog', { name: '自定义时间范围', exact: true });
  const bounds = await dialog.boundingBox();
  expect(bounds.x).toBeGreaterThanOrEqual(0);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(390);
  await expect(dialog.getByRole('button', { name: '应用', exact: true })).toBeInViewport();
});
